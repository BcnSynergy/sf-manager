import { Inject, Injectable, Logger } from '@nestjs/common';
import {
  USER_REPOSITORY,
  type UserRepository,
} from '../../../users/application/ports/user.repository.port';
import type { Role } from '../../../users/domain/role';
import { InvalidCredentialsError } from '../../domain/invalid-credentials.error';
import { LoginBlockedError } from '../../domain/login-blocked.error';
import {
  PASSWORD_HASHER,
  type PasswordHasher,
} from '../../../../shared/application/ports/password-hasher.port';
import {
  LOGIN_FAILURE_LIMITER,
  type LoginFailureLimiter,
} from '../ports/login-failure-limiter.port';
import {
  TOKEN_DENYLIST,
  type TokenDenylist,
} from '../ports/token-denylist.port';
import { TOKEN_ISSUER, type TokenIssuer } from '../ports/token-issuer.port';
import {
  type IssuedRefreshToken,
  RefreshSessionsService,
} from '../services/refresh-sessions.service';

export interface LoginResult {
  user: { id: string; email: string; role: Role };
  accessToken: string;
  // TD-5: the first token of a new refresh family.
  refreshToken: IssuedRefreshToken;
}

// design.md Data Flow (POST /auth/login) + Decisions 7, 9, 10.
@Injectable()
export class LoginUseCase {
  private readonly logger = new Logger(LoginUseCase.name);

  constructor(
    @Inject(USER_REPOSITORY) private readonly userRepository: UserRepository,
    @Inject(PASSWORD_HASHER) private readonly passwordHasher: PasswordHasher,
    @Inject(TOKEN_ISSUER) private readonly tokenIssuer: TokenIssuer,
    @Inject(TOKEN_DENYLIST) private readonly tokenDenylist: TokenDenylist,
    @Inject(LOGIN_FAILURE_LIMITER)
    private readonly loginFailureLimiter: LoginFailureLimiter,
    private readonly refreshSessions: RefreshSessionsService,
  ) {}

  async execute(email: string, password: string): Promise<LoginResult> {
    // Per-email failure limit (login-account-lockout, TD-31): the block is
    // checked BEFORE any lookup or password verification, so a blocked email
    // evaluates no credentials (even a correct password is rejected) and an
    // unknown email costs the same single read as an existing one. A storage
    // error propagates: fail closed (500).
    const block = await this.loginFailureLimiter.getBlock(email);
    if (block.blocked) {
      throw new LoginBlockedError(block.retryAfterSeconds);
    }

    // Default deletedAt: null filter (ADR-010) already applied by the
    // repository — a soft-deleted user resolves to null here, identical to
    // an unknown email (Decision 7).
    const user = await this.userRepository.findByEmail(email);

    // Timing-mitigation (Decision 10): when no user was found, still run a
    // comparably-costed argon2id verify against a fixed dummy hash instead
    // of failing immediately, so the response time doesn't leak whether the
    // email exists. A rejection from the hashing library itself (e.g. a
    // corrupt/malformed hash string) is treated as a failed verification,
    // not an unhandled exception — it must not leak a distinguishable
    // failure signal (500 vs 401) about hash corruption.
    let isValid: boolean;
    try {
      isValid = user
        ? await this.passwordHasher.verify(user.passwordHash, password)
        : await this.passwordHasher.verifyAgainstDummy(password);
    } catch {
      isValid = false;
    }

    if (!user || !isValid) {
      // Unknown, soft-deleted and wrong-password all take this one path, so
      // the counter cannot be used to tell them apart. A storage error here
      // propagates (fail closed, 500) instead of silently uncounting.
      await this.loginFailureLimiter.recordFailure(email);
      throw new InvalidCredentialsError();
    }

    // A valid credential clears the email's counter. Unlike the block check
    // and the failure record, a storage error here must not turn a correct
    // login into a failure: warn (never with the email) and continue.
    try {
      await this.loginFailureLimiter.reset(email);
    } catch (error) {
      this.logger.warn(
        `Login failure counter reset failed: ${error instanceof Error ? error.message : 'unknown error'}`,
      );
    }

    // Only after a successful login — never on a failed attempt, so a
    // brute-force run against this endpoint doesn't also hammer the
    // denylist table with cleanup queries (design.md Data Flow).
    // Purely opportunistic housekeeping — a rejection here (e.g. transient
    // DB error) must never gate an otherwise-successful login; a failed
    // cleanup just means stale rows linger a bit longer, which is harmless.
    try {
      await this.tokenDenylist.deleteExpired();
    } catch {
      // swallow: best-effort cleanup, not a security-relevant operation.
    }

    // Opportunistic, like the denylist cleanup above: never gates login.
    try {
      await this.refreshSessions.deleteExpired();
    } catch {
      // swallow: best-effort cleanup, not a security-relevant operation.
    }

    // jti is generated by the TokenIssuer adapter itself (uuid v4(),
    // deliberately NOT the IdGenerator/UUIDv7 port used for entity ids —
    // Decision 9), not by this use case. `role` and `email` are signed into
    // the token as advisory claims only: AuthenticatedGuard overwrites them
    // with the stored values on every request.
    const accessToken = await this.tokenIssuer.sign({
      sub: user.id,
      email: user.email,
      role: user.role,
    });
    const refreshToken = await this.refreshSessions.start(user.id);

    return {
      user: { id: user.id, email: user.email, role: user.role },
      accessToken,
      refreshToken,
    };
  }
}
